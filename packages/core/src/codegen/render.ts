import { type HttpMethod, type ModuleManifest, type NavEntry, type PageDeclaration, isDynamicRouteSegment } from "@epnexo/sdk";
import { CORE_MODULE_ID } from "../core-module.ts";
import { Registry, compareIds } from "../registry.ts";

/**
 * Rendering of the web app's registration: pure functions from the enabled modules to the text of the generated
 * files. Nothing here touches the filesystem; `generate.ts` decides what to write and what to remove.
 */

/** An enabled module as the generator needs it: its manifest and the name of the package that holds it. */
export interface RegistrationModule {
  manifest: ModuleManifest;
  /** `name` from the module's `package.json`; the web app imports the module through it. */
  packageName: string;
}

export interface RenderedFile {
  /** Relative to the web app root, with forward slashes. */
  path: string;
  content: string;
}

export interface RenderedRegistration {
  files: RenderedFile[];
  /** Package names in dependency order, for the bundler (Next.js `transpilePackages`). */
  packages: string[];
}

/** Everything wrong with the requested registration, found before any file is produced. */
export class RegistrationError extends Error {
  constructor(readonly problems: string[]) {
    super(problems.length === 1 ? problems[0]! : `invalid registration:\n${problems.map((p) => `  - ${p}`).join("\n")}`);
    this.name = "RegistrationError";
  }
}

/**
 * First lines of every generated source file. The generator recognises a file as its own by this text, so it
 * never overwrites or deletes a file that does not start with it.
 */
export const GENERATED_HEADER = [
  "// GENERATED FILE - DO NOT EDIT.",
  "// Generated by @epnexo/core (npm run registry:generate) from the manifests of the enabled modules.",
  "// Changes made here are overwritten on the next run; change the module's manifest instead.",
  "",
  "",
].join("\n");

/** The registry file, relative to the web app root. */
export const REGISTRY_FILE = "src/generated/modules.ts";

/**
 * Paths the web shell owns; a module cannot declare a page at or below any of them. A path is reserved when it
 * equals an entry or sits below it (`/api` reserves `/api/x`, not `/apiary`); `/` reserves only the root itself.
 * The shell UI may add to this list when it is built.
 */
export const RESERVED_PATHS: readonly string[] = ["/", "/apps", "/settings", "/login", "/logout", "/api", "/_next"];

export interface RenderOptions {
  /** Replaces `RESERVED_PATHS`. */
  reservedPaths?: readonly string[];
}

const STATIC_SEGMENT = /^[A-Za-z0-9][A-Za-z0-9._~-]*$/;
const EXTENSION = /\.(?:[cm]?[jt]sx?)$/;

/** A valid dynamic segment with its parameter name erased: `[id]` and `[slug]` are the same position to Next.js. */
const shapeOf = (segment: string): string => (isDynamicRouteSegment(segment) ? segment.replace(/[A-Za-z][A-Za-z0-9_]*(?=\]+$)/, "") : segment);

const normalise = (path: string): string => (path.length > 1 && path.endsWith("/") ? path.slice(0, -1) : path);

const isReserved = (path: string, reserved: readonly string[]): string | undefined =>
  reserved.find((entry) => path === entry || (entry !== "/" && path.startsWith(`${entry}/`)));

/** The specifier the web app imports an entry through: the package name plus the entry without `./` and its extension. */
function specifier(packageName: string, entry: string): string {
  return `${packageName}/${entry.slice(2).replace(EXTENSION, "")}`;
}

function inDependencyOrder(modules: RegistrationModule[]): RegistrationModule[] {
  const byId = new Map(modules.map((m) => [m.manifest.id, m]));
  try {
    // Unsupported platforms are admitted: the lifecycle already decided these modules may run.
    const registry = new Registry({ allowUnsupportedPlatform: true });
    registry.registerCore();
    for (const { manifest } of modules) registry.register(manifest);
    return registry
      .resolveOrder()
      .filter((manifest) => manifest.id !== CORE_MODULE_ID)
      .map((manifest) => byId.get(manifest.id)!);
  } catch (error) {
    throw new RegistrationError([error instanceof Error ? error.message : String(error)]);
  }
}

interface RoutePlan {
  moduleId: string;
  path: string;
  file: string;
  page: PageDeclaration;
  packageName: string;
}

function planRoutes(ordered: RegistrationModule[], reserved: readonly string[], problems: string[]): RoutePlan[] {
  const plans: RoutePlan[] = [];
  const exact = new Map<string, string>();
  // Next.js rejects sibling dynamic folders of one kind with different parameter names. Key: the parent prefix with
  // every name erased, plus the segment's shape; value: the first page that put a named segment there.
  const positions = new Map<string, { segment: string; path: string; moduleId: string }>();

  for (const { manifest, packageName } of ordered) {
    for (const page of manifest.pages ?? []) {
      const path = normalise(page.path);
      const where = `module "${manifest.id}" declares "${path}"`;
      const segments = path === "/" ? [] : path.slice(1).split("/");

      const hit = isReserved(path, reserved);
      if (hit !== undefined) {
        problems.push(`${where}, which is reserved for the shell (${hit === path ? "the path itself" : `below "${hit}"`})`);
        continue;
      }
      const invalid = segments.filter((s) => !STATIC_SEGMENT.test(s) && !isDynamicRouteSegment(s));
      if (invalid.length > 0) {
        problems.push(`${where}, which has an unsupported segment ${invalid.map((s) => `"${s}"`).join(", ")} (use letters, digits, ".", "_", "~", "-", or [name], [...name], [[...name]])`);
        continue;
      }
      const owner = exact.get(path);
      if (owner !== undefined) {
        problems.push(`${where}, which module "${owner}" already declares`);
        continue;
      }
      const claimed: [string, { segment: string; path: string; moduleId: string }][] = [];
      const clashes: string[] = [];
      segments.forEach((segment, index) => {
        if (!isDynamicRouteSegment(segment)) return;
        const key = `/${segments.slice(0, index).map(shapeOf).join("/")}|${shapeOf(segment)}`;
        const first = positions.get(key);
        if (first === undefined) claimed.push([key, { segment, path, moduleId: manifest.id }]);
        else if (first.segment !== segment) {
          clashes.push(`${where} with "${segment}" where module "${first.moduleId}" declares "${first.path}" with "${first.segment}" (Next.js allows one parameter name for a dynamic segment at the same position)`);
        }
      });
      if (clashes.length > 0) {
        problems.push(...clashes);
        continue;
      }
      exact.set(path, manifest.id);
      for (const [key, owner] of claimed) positions.set(key, owner);
      plans.push({ moduleId: manifest.id, path, file: `src/app${path === "/" ? "" : path}/${page.kind === "page" ? "page.tsx" : "route.ts"}`, page, packageName });
    }
  }
  return plans;
}

function renderRoute({ moduleId, path, page, packageName }: RoutePlan): string {
  const from = JSON.stringify(specifier(packageName, page.entry));
  const exported = page.kind === "page" ? ["default", "metadata"] : (page.methods ?? ["GET"] satisfies HttpMethod[]);
  const lines = [`// Module "${moduleId}", ${page.kind} "${path}".`, `export { ${exported.join(", ")} } from ${from};`];
  // Segment config has to be written literally in the route file, so it cannot be re-exported from the module.
  if (page.dynamic !== undefined) lines.push("", "// Segment config is read from this file, so it is written here and not re-exported.", `export const dynamic = ${JSON.stringify(page.dynamic)};`);
  return `${GENERATED_HEADER}${lines.join("\n")}\n`;
}

type RegisteredNav = { moduleId: string } & NavEntry;

/** Ungrouped entries first, then groups by name; inside a group by `order` (entries without one last), label, module id. */
function flattenNavigation(ordered: RegistrationModule[]): RegisteredNav[] {
  const entries = ordered.flatMap(({ manifest }) => manifest.nav.map((entry): RegisteredNav => ({ moduleId: manifest.id, ...entry })));
  return entries.sort(
    (a, b) =>
      Number(a.group !== undefined) - Number(b.group !== undefined) ||
      compareIds(a.group ?? "", b.group ?? "") ||
      (a.order ?? Number.POSITIVE_INFINITY) - (b.order ?? Number.POSITIVE_INFINITY) ||
      compareIds(a.label, b.label) ||
      compareIds(a.moduleId, b.moduleId),
  );
}

const navLiteral = (entry: RegisteredNav): string => {
  const { moduleId, label, href, icon, group, order, permission } = entry;
  return `  ${JSON.stringify({ moduleId, label, href, icon, group, order, permission })},`;
};

const arrayLiteral = (items: string[]): string => `[${items.join(", ")}]`;

function renderRegistry(ordered: RegistrationModule[]): string {
  const imports = ordered.map((m, i) => `import module${i} from ${JSON.stringify(`${m.packageName}/manifest`)};`);
  const navigation = flattenNavigation(ordered);
  return `${GENERATED_HEADER}${[
    'import type { ModuleManifest } from "@epnexo/sdk";',
    ...imports,
    "",
    "/** The enabled modules in dependency order: every module comes after the ones it depends on. */",
    `export const modules: readonly ModuleManifest[] = ${arrayLiteral(ordered.map((_, i) => `module${i}`))};`,
    "",
    "/** One sidebar entry, with the id of the module that contributed it. */",
    "export interface RegisteredNavEntry {",
    "  moduleId: string;",
    "  label: string;",
    "  href: string;",
    "  icon?: string;",
    "  group?: string;",
    "  order?: number;",
    "  permission?: string;",
    "}",
    "",
    "/** Navigation of all enabled modules, flattened and sorted: ungrouped first, then by group, order, label. */",
    navigation.length === 0 ? "export const navigation: readonly RegisteredNavEntry[] = [];" : `export const navigation: readonly RegisteredNavEntry[] = [\n${navigation.map(navLiteral).join("\n")}\n];`,
    "",
    "/** Package names the bundler has to transpile (Next.js `transpilePackages`). */",
    `export const packageNames: readonly string[] = ${arrayLiteral(ordered.map((m) => JSON.stringify(m.packageName)))};`,
  ].join("\n")}\n`;
}

/**
 * The generated files for these enabled modules. Throws `RegistrationError`, listing every problem, when the
 * modules cannot be registered together: no package name, a repeated package, a graph the registry cannot
 * order, two modules claiming one route, a route under a reserved shell path, or a segment that cannot be a
 * folder name. Nothing is produced in that case.
 */
export function renderRegistration(modules: RegistrationModule[], options: RenderOptions = {}): RenderedRegistration {
  const problems: string[] = [];
  const packageOwners = new Map<string, string>();
  for (const { manifest, packageName } of modules) {
    if (packageName.trim() === "") {
      problems.push(`module "${manifest.id}" has no package name (its package.json needs a "name")`);
      continue;
    }
    const owner = packageOwners.get(packageName);
    if (owner !== undefined) problems.push(`package "${packageName}" belongs to both module "${owner}" and module "${manifest.id}"`);
    else packageOwners.set(packageName, manifest.id);
  }
  if (problems.length > 0) throw new RegistrationError(problems);

  const ordered = inDependencyOrder(modules);
  const routes = planRoutes(ordered, options.reservedPaths ?? RESERVED_PATHS, problems);
  if (problems.length > 0) throw new RegistrationError(problems);

  return {
    files: [{ path: REGISTRY_FILE, content: renderRegistry(ordered) }, ...routes.map((route) => ({ path: route.file, content: renderRoute(route) }))],
    packages: ordered.map((m) => m.packageName),
  };
}
